"""Generate Lean-checked rational regression cases from a portable JSON table.

The JSON is also consumed by tests/test_formal_conformance.py.  The Lean
module proves the expected values with `norm_num`; it does not trust the
Python implementations under test.  `--check` detects stale generated proofs.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from fractions import Fraction as Q

ROOT = Path(__file__).resolve().parents[1]
CASES = ROOT / 'tests/formal_cases.json'
OUTPUT = ROOT / 'SeedBayes/Fixtures.lean'


def f(value):
    return Q(str(value))


def rat(x):
    x = f(x)
    return f'({x.numerator} / {x.denominator} : ℝ)' if x.denominator != 1 else f'({x.numerator} : ℝ)'


def compute_cases():
    payload = json.loads(CASES.read_text())
    result = {'bayes': [], 'publication': [], 'search': []}
    for spec in payload['bayes']:
        i, s, lh, lf, lb = (f(spec[x]) for x in ('intent', 'success', 'lh', 'lf', 'lb'))
        h, failure, b = 1-i, i*(1-s), i*s
        z = h*lh + failure*lf + b*lb
        assert z > 0, spec
        numerator = b*((h+failure)*lb-(h*lh+failure*lf))
        row = dict(spec, expected={
            'evidence': str(z), 'before': str(b), 'after': str(b*lb/z),
            'intent_after': str((failure*lf + b*lb)/z),
            'delta': str(b*lb/z-b), 'numerator': str(numerator),
        })
        result['bayes'].append(row)
    for spec in payload['publication']:
        a, st, su, rho = (f(spec[x]) for x in ('alpha', 'st', 'su', 'rho'))
        pt, pu = st+(1-st)*rho, su+(1-su)*rho
        j = a*pt+(1-a)*pu
        assert pt > 0 and j > 0 and a > 0, spec
        before, after = (a*st+(1-a)*su)/j, st/pt
        result['publication'].append(dict(spec, expected={
            'published': str(j), 'before': str(before), 'after': str(after),
            'delta': str(after-before),
            'numerator': str(rho*(1-a)*(st-su)),
        }))
    for spec in payload['search']:
        k, freedom, budget = (int(spec[x]) for x in ('k', 'freedom', 'budget'))
        q = Q(1, 2**k)
        n = 2**min(freedom, budget)
        result['search'].append(dict(spec, expected={'success': str(1-(1-q)**n)}))
    return result


def render():
    table = compute_cases()
    lines = [
        'import SeedBayes.Calculations',
        'import SeedBayes.Publication',
        'import SeedBayes.Search',
        '',
        '/-!',
        '# Exact cross-language conformance cases',
        '',
        'GENERATED by scripts/generate_formal_fixtures.py from',
        'tests/formal_cases.json. Do not edit this file by hand.',
        '',
        'Each example is checked by the Lean kernel, using exact real rational',
        'arithmetic (`norm_num`). The same inputs and expected values are tested',
        'against the production Python and JavaScript code.',
        '-/',
        '',
        'namespace SeedBayes',
        '',
    ]
    for c in table['bayes']:
        i, s, lh, lf, lb = (rat(c[x]) for x in ('intent', 'success', 'lh', 'lf', 'lb'))
        args = f'{i} {s} {lh} {lf} {lb}'
        lines.append(f'-- {c["name"]}')
        for lean_fun, field in [
            ('evidenceOfIntent', 'evidence'),
            ('posteriorOfIntent', 'after'),
            ('posteriorIntentOfIntent', 'intent_after'),
            ('scalarBayesDelta', 'delta'),
            ('scalarBayesNumerator', 'numerator'),
        ]:
            lines.append(f'example : {lean_fun} {args} = {rat(c["expected"][field])} := by')
            lines.append('  norm_num [' + ', '.join(dict.fromkeys((lean_fun, 'evidenceOfIntent', 'posteriorOfIntent'))) + ']')
        lines.append('')
    for c in table['publication']:
        a, st, su, rho = (rat(c[x]) for x in ('alpha', 'st', 'su', 'rho'))
        basic = f'{a} {st} {su} {rho}'
        lines.append(f'-- {c["name"]}')
        lines.append(f'example : mixturePublicationMass {basic} = {rat(c["expected"]["published"])} := by')
        lines.append('  norm_num [mixturePublicationMass, publicationMass]')
        lines.append(f'example : mixturePublishedBackdoor {basic} = {rat(c["expected"]["before"])} := by')
        lines.append('  norm_num [mixturePublishedBackdoor, mixturePublicationMass,')
        lines.append('    publicationMass, mixedSuccess]')
        lines.append(f'example : restrictedPublishedBackdoor {st} {rho} = {rat(c["expected"]["after"])} := by')
        lines.append('  norm_num [restrictedPublishedBackdoor, publicationMass]')
        lhs = f'restrictedPublishedBackdoor {st} {rho} - mixturePublishedBackdoor {basic}'
        lines.append(f'example : {lhs} = {rat(c["expected"]["delta"])} := by')
        lines.append('  norm_num [restrictedPublishedBackdoor, mixturePublishedBackdoor,')
        lines.append('    mixturePublicationMass, publicationMass, mixedSuccess]')
        lines.append(f'example : publicationDeltaNumerator {basic} = {rat(c["expected"]["numerator"])} := by')
        lines.append('  norm_num [publicationDeltaNumerator]')
        lines.append('')
    for c in table['search']:
        k, freedom, budget = (int(c[x]) for x in ('k', 'freedom', 'budget'))
        # Literal q=2^-k and N=2^min(f,b), so a real number of attempts never
        # appears in the Lean statement.
        lines.append(f'-- {c["name"]}')
        lines.append(f'example : independentSuccess (1 / (2 ^ {k}) : ℝ) (2 ^ (min {freedom} {budget})) = {rat(c["expected"]["success"])} := by')
        lines.append('  norm_num [independentSuccess]')
        lines.append('')
    lines.extend(['end SeedBayes', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='fail if Lean file is stale')
    opts = parser.parse_args()
    content = render()
    if opts.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            parser.error('SeedBayes/Fixtures.lean is stale; regenerate it')
        print('Lean fixture module is synchronized with tests/formal_cases.json')
    else:
        OUTPUT.write_text(content)
        print(f'Wrote {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
